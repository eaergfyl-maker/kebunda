/** The entry in the current language; falls back to English field by field. */
export function localizeEntry(entry: GlossaryEntry, lang: Lang): GlossaryEntry {
  if (lang !== "ms") return entry;
  const ms = GLOSSARY_MS[entry.id];
  if (!ms) return entry;
  return { ...entry, term: ms.term, also: ms.also ?? entry.also, plain: ms.plain, why: ms.why };
}
